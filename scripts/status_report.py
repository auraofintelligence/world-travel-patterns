"""Write the generated part of docs/STATUS.md: coverage of every pattern, by level, with the evidence behind it.

Only the text between the generated markers is replaced; the hand-written sections around it stay.

    python scripts/status_report.py
"""
import collections
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from lib import ROOT, VETTING, applies, load_patterns, load_places, read, today  # noqa: E402
from law_repositories import coverage as law_source_coverage  # noqa: E402

START, END = "<!-- generated:start -->", "<!-- generated:end -->"
ENTRY_KEYS = ("laws", "layers", "events", "sites", "items", "closures", "festivals", "cash_card_notes", "footage",
              "operator_register", "foreign_operator", "permits_at_this_level")
HISTORY = ROOT / "data/logs/volume-history.json"
EVIDENCE_KINDS = ("official", "signal", "operational", "legacy-baseline", "community")


def evidence_kind(value):
    """Map a record's evidence field to a short token for the coverage table.

    Some records, especially ancient sites, store a source note in `evidence`
    instead of official/signal. Those notes still count as official when they
    describe official pages or UNESCO data.
    """
    text = (value or "?").strip().lower()
    for token in EVIDENCE_KINDS:
        if text == token or text.startswith(token + " ") or text.startswith(token + ",") or text.startswith(token + ";") or text.startswith(token + "."):
            return token
    if text.startswith("unesco"):
        return "official"
    return "other"


def entries(rec):
    """Count the individual rules, layers, events and sites inside one pattern record."""
    n = 0
    for k in ENTRY_KEYS:
        v = rec.get(k)
        if isinstance(v, list):
            n += len(v)
    if isinstance(rec.get("activities"), dict):
        n += len(rec["activities"])
    return n


def volume_lines(vet, patterns):
    by = collections.Counter()
    recs = 0
    for v in vet.values():
        for pid, rec in v.items():
            if isinstance(rec, dict):
                recs += 1
                by[pid] += entries(rec)
    total = sum(by.values())
    hist = read(HISTORY, {"days": {}})
    day = today().isoformat()
    hist["days"][day] = {"records": recs, "entries": total}
    earlier = sorted(d for d in hist["days"] if d < day)
    HISTORY.write_text(json.dumps(hist, indent=1) + "\n", encoding="utf-8")
    line = f"**Volume:** {recs:,} pattern records holding {total:,} individual rules, layers, events, sites and checks"
    if earlier:
        prev = hist["days"][earlier[-1]]
        line += (f" ({recs - prev['records']:+,} records and {total - prev['entries']:+,} entries since {earlier[-1]})")
    names = {k: p["name"] for k, p in patterns.items()}
    top = ", ".join(f"{names.get(k, k)} {n:,}" for k, n in by.most_common(8))
    return [line + ".", "", f"**Largest by entries:** {top}.", ""]


def level(pid, p):
    if "/" not in pid:
        return "spine"
    if p.get("source_kind") == "first-level" or p.get("kind") == "state":
        return "region"
    return "other"


def pct(a, b):
    return f"{round(100 * a / b)}%" if b else "n/a"


def main():
    places, patterns = load_places(), load_patterns()
    vet = {read(f)["place"]: read(f)["patterns"] for f in VETTING.glob("*.json")}
    levels = collections.Counter(level(k, p) for k, p in places.items())
    photos = read(ROOT / "site/data/place-photos.json", {"photos": {}})["photos"]
    acts = collections.Counter(a["status"] for v in vet.values() if v.get("activities") for a in v["activities"]["activities"].values())
    lines = [START, "", f"_Generated by `scripts/status_report.py` on {today().isoformat()}._", "",
             f"**Places:** {len(places):,} in the tree: {levels['spine']} countries and territories, {levels['region']:,} states and regions, "
             f"{levels['other']:,} others (councils, electorates, islands, nations, permit zones, sites).", "",
             f"**Places with any record:** {len(vet):,}.", "",
             *volume_lines(vet, patterns),
             "| Pattern | Countries and territories | Evidence (countries) | States and regions | Fills by |", "| --- | --- | --- | --- | --- |"]
    for pid, pat in patterns.items():
        if pat.get("method") == "machine":
            lines.append(f"| {pat['name']} | every destination, daily | official | uses the country's | GitHub Action |")
            continue
        cells = []
        for lv in ("spine", "region"):
            ids = [k for k, p in places.items() if level(k, p) == lv and applies(pat, p) and k != "au"]
            have = [k for k in ids if pid in vet.get(k, {})]
            cells.append((len(have), len(ids), collections.Counter(evidence_kind(vet[k][pid].get("evidence")) for k in have)))
        (sh, st, ev), (rh, rt, _) = cells
        evtxt = ", ".join(f"{n} {e}" for e, n in ev.most_common()) or "none"
        region = f"{rh:,} of {rt:,} ({pct(rh, rt)})" if rt else f"uses the country's ({pat['inherit']})"
        lines.append(f"| {pat['name']} | {sh} of {st} ({pct(sh, st)}) | {evtxt} | {region} | {pat['method']} |")
    total = sum(acts.values())
    repos = read(ROOT / "data/law-repositories.json", {"places": {}})
    law = law_source_coverage(repos, places)
    lines += ["", f"**Activities:** {total:,} activity checks across {sum(1 for v in vet.values() if v.get('activities'))} places: "
              + ", ".join(f"{n:,} {s}" for s, n in acts.most_common()) + f". Still to confirm in writing: {pct(acts['confirm-in-writing'] + acts['confirm'], total)}.",
              "", f"**Law-source map:** {law['verified']:,} of {law['first_level']:,} states and regions have at least one verified official law source "
              f"(the official page loaded when checked, or was later marked read directly). "
              f"A further {law['listed_unverified']:,} have a listed source that has not yet been confirmed. "
              f"Of {law['spine']} countries and territories, {law['spine_with_url']} have a law-source URL and "
              f"{law['no_online_source']} are marked as having no official online source found.",
              "", f"**Place photos:** {len(photos)} places show a photo; {sum(1 for p in photos.values() if p.get('review') == 'pending')} await Luke's review.",
              "", END]
    path = ROOT / "docs/STATUS.md"
    text = path.read_text(encoding="utf-8") if path.exists() else f"# Status\n\n{START}\n{END}\n"
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    path.write_text(head + "\n".join(lines) + tail, encoding="utf-8")
    print("docs/STATUS.md updated")


if __name__ == "__main__":
    main()
